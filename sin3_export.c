#define WBASIC_EMBEDDED_BUILD 1
#define WBASIC_NO_UI 1
#include "wbasic.c"

static const char *embedded_bas =
"10 REM TEXT SINE WAVE FAST USING LOCATE (NO SCROLL)\n"
"20 INPUT \"ENTER NUMBER OF COLUMNS: \"; COLS\n"
"30 IF COLS < 10 THEN COLS = 10\n"
"40 IF COLS > 80 THEN COLS = 80\n"
"\n"
"50 ROWS = 24\n"
"60 AMPL = COLS / 2\n"
"70 CENTER = COLS / 2\n"
"80 PHASE = 0\n"
"85 SPEED 85\n"
"\n"
"90 DIM OLDX(30)\n"
"100 FOR R = 1 TO ROWS\n"
"110 OLDX(R) = 0\n"
"120 NEXT R\n"
"\n"
"130 CLS\n"
"\n"
"140 REM MAIN LOOP\n"
"150 K$ = INKEY$\n"
"160 IF K$ = \"q\" THEN K$ = \"Q\"\n"
"170 IF K$ = \"Q\" THEN END\n"
"\n"
"180 REM OPTIONAL STATUS LINE\n"
"190 LOCATE 25,1,0\n"
"200 PRINT \"Q=QUIT   COLS=\"; COLS; \"   PHASE=\"; PHASE; \"      \";\n"
"\n"
"210 FOR Y = 0 TO ROWS - 1\n"
"220 ROW = Y + 1\n"
"\n"
"230 ANG = (Y / (ROWS - 1.0)) * 6.2831853 + PHASE\n"
"240 X = CENTER + AMPL * SIN(ANG)\n"
"250 X = INT(X)\n"
"\n"
"260 IF X < 1 THEN X = 1\n"
"270 IF X > COLS THEN X = COLS\n"
"\n"
"280 REM ERASE PREVIOUS STAR ON THIS ROW\n"
"290 IF OLDX(ROW) = 0 THEN GOTO 320\n"
"300 LOCATE ROW,OLDX(ROW),0\n"
"310 PRINT \" \";\n"
"\n"
"320 REM DRAW NEW STAR\n"
"330 LOCATE ROW,X,0\n"
"340 PRINT \"*\";\n"
"\n"
"350 OLDX(ROW) = X\n"
"360 NEXT Y\n"
"\n"
"370 PHASE = PHASE + 0.15\n"
"\n"
"400 GOTO 150\n"
;

int main(int argc, char **argv){ return wbasic_run_embedded(argc, argv, embedded_bas); }
